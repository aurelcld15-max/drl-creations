CREATE OR REPLACE FUNCTION public.drl_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

DO $$
DECLARE
    table_name TEXT;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['users', 'products', 'creations', 'site_settings', 'faq', 'custom_requests']
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS drl_updated_at ON public.%I', table_name);
        EXECUTE format(
            'CREATE TRIGGER drl_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.drl_set_updated_at()',
            table_name
        );
    END LOOP;
END;
$$;

