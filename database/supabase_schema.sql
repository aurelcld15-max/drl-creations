CREATE TABLE IF NOT EXISTS public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supabase_uid UUID UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(191) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    phone VARCHAR(40),
    avatar VARCHAR(255),
    role VARCHAR(16) NOT NULL DEFAULT 'client' CHECK (role IN ('client', 'admin')),
    oauth_provider VARCHAR(16) NOT NULL DEFAULT 'local' CHECK (oauth_provider IN ('local', 'google', 'apple')),
    oauth_id VARCHAR(191),
    email_verified_at TIMESTAMP,
    verification_token VARCHAR(128),
    reset_token VARCHAR(128),
    reset_expires_at TIMESTAMP,
    failed_login_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMP,
    preferred_lang VARCHAR(2) NOT NULL DEFAULT 'fr' CHECK (preferred_lang IN ('fr', 'en')),
    preferred_theme VARCHAR(8) NOT NULL DEFAULT 'light' CHECK (preferred_theme IN ('light', 'dark')),
    is_active SMALLINT NOT NULL DEFAULT 1,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_role ON public.users (role);
CREATE INDEX IF NOT EXISTS idx_users_oauth ON public.users (oauth_provider, oauth_id);
CREATE INDEX IF NOT EXISTS idx_users_verification ON public.users (verification_token);
CREATE INDEX IF NOT EXISTS idx_users_reset ON public.users (reset_token);

CREATE TABLE IF NOT EXISTS public.categories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_fr VARCHAR(120) NOT NULL,
    name_en VARCHAR(120) NOT NULL,
    slug VARCHAR(140) NOT NULL UNIQUE,
    type VARCHAR(16) NOT NULL DEFAULT 'both' CHECK (type IN ('creation', 'product', 'both')),
    description_fr TEXT,
    description_en TEXT,
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active SMALLINT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_categories_type_active ON public.categories (type, is_active, sort_order);

CREATE TABLE IF NOT EXISTS public.products (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    reference VARCHAR(60) NOT NULL UNIQUE,
    slug VARCHAR(191) NOT NULL UNIQUE,
    name_fr VARCHAR(180) NOT NULL,
    name_en VARCHAR(180) NOT NULL,
    description_fr TEXT NOT NULL,
    description_en TEXT,
    fabric_details VARCHAR(255),
    sizes_available VARCHAR(150) DEFAULT 'S, M, L, Sur-mesure',
    price NUMERIC(12,2) CHECK (price IS NULL OR price >= 0),
    currency VARCHAR(10) NOT NULL DEFAULT 'FCFA',
    pricing_mode VARCHAR(16) NOT NULL DEFAULT 'fixed' CHECK (pricing_mode IN ('fixed', 'negotiable', 'on_request')),
    availability_status VARCHAR(16) NOT NULL DEFAULT 'available' CHECK (availability_status IN ('available', 'sold', 'archived', 'hidden')),
    is_featured SMALLINT NOT NULL DEFAULT 0,
    views_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category_id);
CREATE INDEX IF NOT EXISTS idx_products_status_featured ON public.products (availability_status, is_featured);
CREATE INDEX IF NOT EXISTS idx_products_pricing ON public.products (pricing_mode);

CREATE TABLE IF NOT EXISTS public.product_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES public.products(id) ON DELETE CASCADE ON UPDATE CASCADE,
    image_path VARCHAR(255) NOT NULL,
    alt_text VARCHAR(180),
    is_primary SMALLINT NOT NULL DEFAULT 0,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_product_images_product ON public.product_images (product_id, is_primary, sort_order);

CREATE TABLE IF NOT EXISTS public.creations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES public.categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    reference VARCHAR(60) NOT NULL UNIQUE,
    slug VARCHAR(191) NOT NULL UNIQUE,
    name_fr VARCHAR(180) NOT NULL,
    name_en VARCHAR(180) NOT NULL,
    description_fr TEXT NOT NULL,
    description_en TEXT,
    estimated_delay VARCHAR(100) DEFAULT '7 à 14 jours ouvrés',
    customizable_options VARCHAR(255) DEFAULT 'Tissu, Couleur, Broderie, Mensurations sur-mesure',
    indicative_price NUMERIC(12,2) CHECK (indicative_price IS NULL OR indicative_price >= 0),
    publication_status VARCHAR(16) NOT NULL DEFAULT 'published' CHECK (publication_status IN ('published', 'unpublished', 'draft')),
    is_featured SMALLINT NOT NULL DEFAULT 0,
    views_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_creations_category ON public.creations (category_id);
CREATE INDEX IF NOT EXISTS idx_creations_status_featured ON public.creations (publication_status, is_featured);

CREATE TABLE IF NOT EXISTS public.creation_images (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creation_id INTEGER NOT NULL REFERENCES public.creations(id) ON DELETE CASCADE ON UPDATE CASCADE,
    image_path VARCHAR(255) NOT NULL,
