CREATE OR REPLACE FUNCTION public.drl_claim_first_admin(p_user_id INTEGER)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    bootstrap_value TEXT;
BEGIN
    INSERT INTO public.site_settings (setting_key, setting_value, setting_group)
    VALUES ('admin_bootstrap_claimed', '0', 'system')
    ON CONFLICT (setting_key) DO NOTHING;

    SELECT setting_value INTO bootstrap_value
    FROM public.site_settings
    WHERE setting_key = 'admin_bootstrap_claimed'
    FOR UPDATE;

    IF bootstrap_value = '1' THEN
        RETURN FALSE;
    END IF;

    IF EXISTS (SELECT 1 FROM public.users WHERE role = 'admin') THEN
        UPDATE public.site_settings SET setting_value = '1' WHERE setting_key = 'admin_bootstrap_claimed';
        RETURN FALSE;
    END IF;

    UPDATE public.users
    SET role = 'admin', email_verified_at = COALESCE(email_verified_at, CURRENT_TIMESTAMP)
    WHERE id = p_user_id AND role = 'client' AND is_active = 1 AND email_verified_at IS NOT NULL;

    IF NOT FOUND THEN
        RETURN FALSE;
    END IF;

    UPDATE public.site_settings SET setting_value = '1' WHERE setting_key = 'admin_bootstrap_claimed';
    RETURN TRUE;
END;
$$;

CREATE OR REPLACE FUNCTION public.drl_sync_auth_profile()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    profile_id INTEGER;
    provider_name TEXT;
BEGIN
    provider_name := COALESCE(NEW.raw_app_meta_data ->> 'provider', 'email');
    IF provider_name NOT IN ('google', 'apple') THEN
        provider_name := 'local';
    END IF;

    INSERT INTO public.users (supabase_uid, first_name, last_name, email, phone, role, oauth_provider, email_verified_at, is_active)
    VALUES (
        NEW.id,
        COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'first_name', ''), 'Client'),
        COALESCE(NULLIF(NEW.raw_user_meta_data ->> 'last_name', ''), 'DRL'),
        LOWER(NEW.email),
        NULLIF(NEW.raw_user_meta_data ->> 'phone', ''),
        'client',
        provider_name,
        NEW.email_confirmed_at,
        1
    )
    ON CONFLICT (email) DO UPDATE SET
        supabase_uid = EXCLUDED.supabase_uid,
        first_name = COALESCE(NULLIF(EXCLUDED.first_name, 'Client'), public.users.first_name),
        last_name = COALESCE(NULLIF(EXCLUDED.last_name, 'DRL'), public.users.last_name),
        phone = COALESCE(EXCLUDED.phone, public.users.phone),
        oauth_provider = CASE WHEN EXCLUDED.oauth_provider = 'local' THEN public.users.oauth_provider ELSE EXCLUDED.oauth_provider END,
        email_verified_at = COALESCE(public.users.email_verified_at, EXCLUDED.email_verified_at),
        updated_at = CURRENT_TIMESTAMP
    RETURNING id INTO profile_id;

    IF NEW.email_confirmed_at IS NOT NULL THEN
        PERFORM public.drl_claim_first_admin(profile_id);
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS drl_auth_profile_sync ON auth.users;
CREATE TRIGGER drl_auth_profile_sync
AFTER INSERT OR UPDATE ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.drl_sync_auth_profile();

REVOKE EXECUTE ON FUNCTION public.drl_claim_first_admin(INTEGER) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.drl_sync_auth_profile() FROM PUBLIC, anon, authenticated;

