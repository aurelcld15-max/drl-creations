ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (
    bucket_id = 'drl-media'
    AND EXISTS (
        SELECT 1
        FROM public.users u
        WHERE u.supabase_uid = auth.uid()
          AND u.is_active = 1
          AND (
              u.role = 'admin'
              OR (
                  (storage.foldername(name))[1] = 'profiles'
                  AND (storage.foldername(name))[2] = auth.uid()::TEXT
              )
          )
    )
);

