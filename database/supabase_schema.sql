CREATE TABLE IF NOT EXISTS public.favorites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    item_type VARCHAR(16) NOT NULL DEFAULT 'product' CHECK (item_type IN ('product', 'creation')),
    product_id INTEGER REFERENCES public.products(id) ON DELETE CASCADE ON UPDATE CASCADE,
    creation_id INTEGER REFERENCES public.creations(id) ON DELETE CASCADE ON UPDATE CASCADE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_favorites_user_product UNIQUE (user_id, item_type, product_id),
    CONSTRAINT uk_favorites_user_creation UNIQUE (user_id, item_type, creation_id)
